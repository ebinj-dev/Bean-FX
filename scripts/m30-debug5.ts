process.env.BEANFX_MEDIA_WORKER_AUTOSTART = "0";
const { resolveReviewActor, loadRevision } = await import("../src/lib/review-access.ts");
const { sha256Hex } = await import("../src/lib/collab.ts");
const { PrismaClient } = await import("@prisma/client");
const db = new PrismaClient();
const cookie = process.argv[2];
const revId = process.argv[3];
const raw = cookie.split("=").slice(1).join("=");
const [linkId, guestToken] = decodeURIComponent(raw).split(".");
console.log("linkId:", linkId.slice(-6), "tokenLen:", guestToken.length);
const link = await db.reviewLink.findUnique({ where: { id: linkId } });
console.log("link found:", !!link, "revMatch:", link?.revisionId === revId, "state:", link?.state, "notExpired:", link ? link.expiresAt > new Date() : false);
console.log("tokenHashMatch:", link ? link.tokenHash === sha256Hex(guestToken) : false);
const guest = await db.guestAccess.findFirst({ where: { linkId, tokenHash: sha256Hex(guestToken) } });
console.log("guest row:", !!guest);
const fakeReq = { headers: { get: (k: string) => (k === "cookie" ? cookie : null) } } as unknown as import("next/server").NextRequest;
const r = await resolveReviewActor(revId, fakeReq);
console.log("resolution:", r.ok ? `OK ${r.actor.kind}` : `ERROR ${r.error.status}`);
await db.$disconnect(); process.exit(0);
