#!/usr/bin/env bash
# One-command M16 push (persistent credential; plain fast-forward push, never force).
set -euo pipefail
SRC=/home/z/my-project
AUTH="$SRC/scripts/git-cred-helper.sh"
BRANCH=feature/ai-creative-studio
CLONE=/tmp/beanfx-push-m16

bash "$SRC/scripts/gh-auth-restore.sh" || { echo "FATAL: GitHub authentication not ready"; exit 1; }
test -x "$AUTH" || { echo "FATAL: credential helper $AUTH missing"; exit 1; }

rm -rf "$CLONE"
git clone -q -c credential.helper="!$AUTH" "https://github.com/ebinj-dev/Bean-FX.git" "$CLONE"
cd "$CLONE"
echo "=== tips before push ==="
git ls-remote origin refs/heads/"$BRANCH" refs/heads/main | cat
git checkout "$BRANCH" 2>/dev/null || git checkout -b "$BRANCH" "origin/$BRANCH"
BASE=$(git rev-parse HEAD)
echo "branch tip before push: $BASE"
git merge-base --is-ancestor 8c54096f241fb0e04b403b2901ea2148104e1894 HEAD && echo "M15 8c54096 IS in history"

bash "$SRC/scripts/overlay-m16.sh" "$CLONE"

if git status --porcelain | grep -q .; then
  echo "=== secret scan (M16 set) ==="
  if git diff --name-only "$BASE" | while read -r f; do
        grep -lE "gho_[A-Za-z0-9]{20,}|ghp_[A-Za-z0-9]{20,}|github_pat_|sk-[A-Za-z0-9]{20,}|BEGIN (RSA|OPENSSH) PRIVATE KEY" "$f" 2>/dev/null
      done | grep -q .; then
    echo "SECRET SCAN FAILED — aborting push"; exit 1
  fi
  echo "(clean)"
  git add -A
  git -c user.name="Z User" -c user.email="z@container" commit -m "feat(m16): professional editing engine & real-time studio

Root cause audit (docs/M16_ENGINE_AUDIT.md): M15's remaining limitations
were traced to (1) an accumulating per-tick rounding clock, (2) no clip-
boundary preloading, (3) unguarded seeks, (4) a 4-element audio pool with
no pan/master/automation, (5) NO sequence-to-video renderer at all, (6) a
tiny effects set with implicit preview parity, (7) per-frame full-tree
re-renders. M16 fixes the engine — no UI redesign, all M15 preserved.

- playback engine (lib/editor/playback.ts): framework-free
  PlaybackController — ANCHOR-BASED clock (playhead = start + elapsed × fps,
  rounded once per tick; no accumulated drift; rational FPS), seek
  generations (stale media callbacks dropped), dropped-frame telemetry,
  hidden-tab suspend/resume; a frame bus lets the monitor, timeline
  playhead and transport timecode paint per-frame IMPERATIVELY — React
  re-renders stay transport/seek/edit-level only
- monitor: double-buffered video pool (the idle element preloads the next
  same-track clip; boundaries swap instead of re-loading), decode-error
  surfacing, preview filter chains generated by the SAME module as export
- audio (lib/editor/audio-mixer.ts): Web Audio multi-track mixer — every
  audible clip decoded once (LRU buffer cache) and scheduled as
  AudioBufferSourceNodes on the AudioContext clock mapped from timeline
  seconds; clip gain × fade ramps, stereo pan, per-track mute/solo nodes,
  master headroom clamp, horizon refill, seek reschedule; element-pool
  fallback preserved and labeled honestly (removes the M15 4-contributor
  cap where Web Audio exists)
- editing operations (lib/editor/edits.ts): INSERT (shifts later clips),
  OVERWRITE (tail/head trims + middle split), ROLL (shared boundary moves,
  duration preserved; extension only with REAL probed source durations —
  honest refusal otherwise), LIFT (gap left), EXTRACT (gap closed), group
  move with collision refusal — all compiled to existing reversible M1
  commands as atomic batches; roll wired into the context menu with real
  asset durations from the media library
- effects/color (lib/editor/filters.ts + additive EffectType):
  brightness/contrast/saturation/exposure/temperature/tint/highlights/
  shadows/sharpen — ONE registry generates BOTH the CSS preview filter and
  the FFmpeg export chain (eq merge honoring the single-instance rule);
  sharpen is export-only and labeled ≈ where the preview approximates;
  inspector EFFECTS section: parameters, ON/OFF, reorder, reset, bypass,
  live parity readout (preview CSS + export FFmpeg strings); COLOR panel
  with reset; browser E2E verifies real pixel desaturation (grayscale
  spread 0 in the monitor screenshot)
- THE missing export path: RENDER_TIMELINE durable job
  (lib/publish/timeline-render.ts) renders the canonical sequence — per-clip
  trim/speed/fit/effects/fades, overlay chain in track order, caption
  drawtext windows, NIIKI graphic filters, per-clip audio trim/speed/
  adelay/volume/afade → amix over a silence bed; ffprobe-validated output
  registered as a real ExportFile; API + export-drawer panel with real job
  status; per-asset ffprobe decides audio availability (video-only sources
  handled); render window defaults to the sequence end (a sentinel default
  that once produced a 33-million-second render is fixed)
- timeline: real clip thumbnails (decoded frames, LRU-cached,
  promise-deduped), bus-driven playhead, Lift/Extract/Roll context menu,
  Shift+Arrows group move
- canvas: multi-selection with group moves, Escape cancellation, arrow-key
  nudging (Shift ×10)
- AI: MY AI context now includes effects, caption text, volume/fades and
  track structure; Ctrl/Cmd+S flushes the autosave; beforeunload guard
- tests: m16-core 19/19 (anchor clock no-drift, seek generations, end-stop,
  frame bus, insert/overwrite/roll/lift/extract/group against the REAL
  engine, filter mapping incl. eq-merge + additive back-compat, render
  graph incl. captions/missing-media + a REAL ffmpeg render validated by
  ffprobe); browser E2E: M15 flow regression + M16 playback advance,
  seek, pixel-verified grayscale, inspector parity readout, AI context,
  durable render + FFprobe (video=1 audio=1 dur=4.00); 14 screenshots;
  build clean. Pre-existing environment failures in 2 M13 OpenCV suites
  (TrackerCSRT needs opencv-contrib; sandbox has mainline 4.13) verified
  identical WITHOUT M16 changes — reported, not hidden"
  SHA=$(git rev-parse HEAD)
else
  SHA=$(git rev-parse HEAD)
  echo "no diff after overlay — nothing to commit"
fi

git push origin "$BRANCH"
echo "=== pushed local SHA: $SHA ==="
sleep 2
REMOTE_TIP=$(git ls-remote origin refs/heads/"$BRANCH" | awk '{print $1}')
REMOTE_MAIN=$(git ls-remote origin refs/heads/main | awk '{print $1}')
echo "remote $BRANCH tip: $REMOTE_TIP"
echo "remote main tip:   $REMOTE_MAIN"
[ "$REMOTE_TIP" = "$SHA" ] && echo "VERIFIED: remote branch tip == pushed commit" || { echo "MISMATCH"; exit 1; }
git merge-base --is-ancestor 8c54096f241fb0e04b403b2901ea2148104e1894 "$REMOTE_TIP" && echo "M15 remains in remote history"
echo "=== pushed files ==="
git diff --name-only "$BASE" HEAD
echo "PUSH_COMPLETE"
