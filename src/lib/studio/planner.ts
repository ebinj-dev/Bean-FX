/**
 * Social Video Studio — production planner (M8.1 §3).
 *
 * Uses the M8 LLM gateway (real, configured provider) to turn a validated
 * brief into a schema-validated ProductionPlan; supports per-scene
 * regeneration without touching other scenes (§4). When no provider is
 * configured, a clearly-labeled deterministic planner produces an honest
 * outline plan (scenes derived from the topic — NOT model reasoning).
 * No fake research: the planner prompt FORBIDS inventing sources; plans
 * carry only user-supplied or empty attribution.
 */
import { db } from "@/lib/db";
import { ProductionPlanSchema, PlanSceneSchema, normalizeProductionPlan, estimateSpeechSec, PRODUCTION_PLAN_SCHEMA_VERSION, type ProductionPlan, type PlanScene } from "./plan";
import { type StudioBrief, PLATFORM_PROFILES } from "./brief";
import { chatValidated } from "@/lib/my-ai/gateway/structured";
import { llmHealth, LLMError } from "@/lib/my-ai/gateway/provider";
import { recordUsage } from "@/lib/my-ai/gateway/usage";
import { z } from "zod";

const LANGUAGE_NAMES: Record<string, string> = { en: "English", ta: "Tamil" };

const PLANNER_SYSTEM = `You are the Social Video Studio planner inside BEAN FX, a frame-accurate video editor.
Produce ONLY a JSON production plan — no prose, no markdown fences.
Language: write ALL narration, captions, on-screen text, hook, intro and CTA in the REQUESTED language (English or Tamil).
Structure:
{"schemaVersion":1,"topicSummary":"...","hook":"...","intro":"...","scenes":[{"sceneNumber":1,"durationSec":6,"narration":"...","visualDescription":"...","footageNeed":"searchable footage description","brollNote":"optional","onScreenText":"short overlay text or empty","captionText":"caption for this scene or empty","audioNote":"e.g. upbeat music bed","transition":"CUT"}],"musicMood":"upbeat","closingCta":"...","fullScript":"all narration joined","sources":[]}
Rules:
- sceneNumber starts at 1, consecutive, ascending.
- durationSec 2..60 per scene; total should approximate the requested duration.
- narration is what the voiceover reads aloud (natural spoken sentences).
- visualDescription/footageNeed describe REALISTIC stock or generated visuals — never claim a specific copyrighted work or brand.
- sources: ONLY include entries the user supplied in the brief (they will not be there) — otherwise [] — NEVER invent citations, statistics, or quotes.
- transitions from: CUT, CROSS_DISSOLVE, FADE_TO_BLACK, FADE_FROM_BLACK, WIPE_LEFT, WIPE_RIGHT, SLIDE_LEFT, SLIDE_RIGHT.`;

export interface PlannerOutcome {
  plan: ProductionPlan;
  mode: "llm" | "deterministic-fallback";
  note: string;
}

function targetSceneCount(brief: StudioBrief): number {
  const avg = brief.platform.startsWith("youtube_landscape") ? 8 : 5;
  return Math.max(2, Math.min(24, Math.round(brief.durationSec / avg)));
}

/** Build a bounded planner prompt from the validated brief. */
function briefPrompt(brief: StudioBrief): string {
  const profile = PLATFORM_PROFILES[brief.platform];
  return `Brief:
- Topic: ${brief.topic}
- Keywords: ${brief.keywords.join(", ") || "(none)"}
- Audience: ${brief.audience || "general"}
- Language: ${LANGUAGE_NAMES[brief.language]}
- Objective: ${brief.objective}
- Platform: ${profile.label} (${profile.aspect}, max ${profile.maxDurationSec}s)
- Target duration: ${brief.durationSec}s across ~${targetSceneCount(brief)} scenes
- Tone/style: ${brief.tone}
- Visual style: ${brief.visualStyle}
- Music mood: ${brief.musicMood}
- Captions: ${brief.captionsEnabled ? "yes" : "no"}
${brief.customScript ? `- The USER supplied this script — use it as the narration verbatim, split across scenes sensibly:\n"""\n${brief.customScript.slice(0, 6000)}\n"""` : ""}

Produce the production plan JSON now.`;
}

/**
 * Create + persist a studio plan (and its scene rows) for a brief.
 * Uses the real LLM when configured; otherwise the labeled fallback.
 */
export async function createStudioPlan(userId: string, planId: string, brief: StudioBrief): Promise<PlannerOutcome> {
  await db.studioPlan.update({ where: { id: planId }, data: { status: "PLANNING" } }).catch(() => undefined);
  const health = await llmHealth();
  let outcome: PlannerOutcome;
  if (!health.ok) {
    const plan = deterministicPlan(brief);
    outcome = { plan, mode: "deterministic-fallback", note: `LLM provider unavailable (${health.detail}); an outline plan was generated by rules — NOT model reasoning.` };
  } else {
    try {
      const { data, model } = await chatValidated(
        userId,
        z.preprocess(normalizeProductionPlan, ProductionPlanSchema),
        [
          { role: "system", content: PLANNER_SYSTEM },
          { role: "user", content: briefPrompt(brief) },
        ],
        {
          purpose: "studio-planner",
          temperature: 0.4,
          timeoutMs: Number(process.env.BEANFX_STUDIO_PLANNER_TIMEOUT_MS ?? 120_000),
          onUsage: (r) => {
            void recordUsage(userId, { content: "", model: r.model, provider: "zai", usage: r.usage, latencyMs: 0 }, "studio-planner");
          },
        },
      );
      outcome = { plan: data, mode: "llm", note: `Production plan written by ${model}; edit any scene and regenerate it individually.` };
    } catch (err) {
      const detail = err instanceof LLMError ? `${err.code}: ${err.message.slice(0, 200)}` : err instanceof Error ? err.message.slice(0, 200) : "unknown error";
      const plan = deterministicPlan(brief);
      outcome = { plan, mode: "deterministic-fallback", note: `LLM planning failed (${detail}); rule-based outline produced — NOT model reasoning.` };
    }
  }
  await persistScenes(planId, userId, outcome.plan, brief);
  await db.studioPlan.update({
    where: { id: planId },
    data: {
      status: "SCENES_READY",
      planJson: JSON.stringify(outcome.plan),
      plannerMode: outcome.mode === "llm" ? outcome.mode : "deterministic-fallback",
      sceneCount: outcome.plan.scenes.length,
    },
  });
  return outcome;
}

/** Persist plan scenes as editable StudioScene rows (replace-all semantics). */
async function persistScenes(planId: string, userId: string, plan: ProductionPlan, brief: StudioBrief): Promise<void> {
  await db.studioScene.deleteMany({ where: { planId } });
  let n = 0;
  for (const s of plan.scenes) {
    await db.studioScene.create({
      data: {
        planId,
        userId,
        sceneNumber: s.sceneNumber,
        durationSec: s.durationSec,
        narration: s.narration,
        visualDescription: s.visualDescription,
        footageNeed: s.footageNeed,
        onScreenText: s.onScreenText,
        captionText: s.captionText || s.narration.slice(0, 400),
        audioNote: s.audioNote,
        transition: s.transition,
        status: "EMPTY",
        attributionJson: JSON.stringify({ language: brief.language }),
      },
    });
    n = s.sceneNumber;
  }
  void n;
}

/** Regenerate ONE scene (§4): targeted LLM call, other scenes untouched. */
export async function regenerateScene(userId: string, planId: string, sceneId: string, instruction?: string): Promise<{ ok: boolean; scene?: PlanScene; mode: string; note: string }> {
  const row = await db.studioScene.findFirst({ where: { id: sceneId, userId, planId } });
  const planRow = await db.studioPlan.findFirst({ where: { id: planId, userId } });
  if (!row || !planRow) return { ok: false, mode: "none", note: "Scene or plan not found or not owned." };
  const brief = JSON.parse(planRow.briefJson) as StudioBrief;
  const siblings = await db.studioScene.findMany({ where: { planId, sceneNumber: { not: row.sceneNumber } }, orderBy: { sceneNumber: "asc" }, select: { sceneNumber: true, narration: true, durationSec: true } });

  const health = await llmHealth();
  if (!health.ok) {
    return { ok: false, mode: "deterministic-fallback", note: `Scene regeneration needs the LLM provider (${health.detail}); edit the scene fields manually instead.` };
  }
  try {
    const schema = z.object({ scene: PlanSceneSchema });
    const { data, model } = await chatValidated(
      userId,
      z.preprocess((raw) => (typeof raw === "object" && raw !== null && !("scene" in (raw as object)) ? { scene: raw } : raw), schema),
      [
        {
          role: "system",
          content: `${PLANNER_SYSTEM}\nThis task rewrites ONE scene only. Respond with {"scene": {...}} using the SAME schema for that single scene.`,
        },
        {
          role: "user",
          content: `Brief: ${briefPrompt(brief).slice(0, 1200)}
Scene #${row.sceneNumber} to regenerate${instruction ? ` — user instruction: ${instruction.slice(0, 300)}` : ""}.
Current scene: narration="${row.narration.slice(0, 500)}"; visual="${row.visualDescription.slice(0, 300)}"; duration=${row.durationSec}s; onScreenText="${row.onScreenText}".
Sibling scenes (do NOT copy them; keep continuity): ${siblings.map((s) => `#${s.sceneNumber}: "${s.narration.slice(0, 80)}…" (${s.durationSec}s)`).join(" | ") || "(none)"}
Produce the replacement scene JSON.`,
        },
      ],
      {
        purpose: "studio-scene-regen",
        temperature: 0.5,
        timeoutMs: Number(process.env.BEANFX_STUDIO_PLANNER_TIMEOUT_MS ?? 120_000),
        onUsage: (r) => {
          void recordUsage(userId, { content: "", model: r.model, provider: "zai", usage: r.usage, latencyMs: 0 }, "studio-scene-regen");
        },
      },
    );
    const scene = data.scene;
    await db.studioScene.update({
      where: { id: sceneId },
      data: {
        narration: scene.narration,
        visualDescription: scene.visualDescription,
        footageNeed: scene.footageNeed,
        brollNote: scene.brollNote,
        onScreenText: scene.onScreenText,
        captionText: scene.captionText || scene.narration.slice(0, 400),
        audioNote: scene.audioNote,
        durationSec: scene.durationSec,
        transition: scene.transition,
        // Asset no longer guaranteed to match the new visual.
        assetId: null,
        assetKind: null,
        assetSource: "none",
        narrationAssetId: null,
        status: "EMPTY",
      },
    });
    await refreshPlanJson(planId, userId);
    return { ok: true, scene, mode: `llm:${model}`, note: `Scene #${scene.sceneNumber} regenerated by ${model}.` };
  } catch (err) {
    const detail = err instanceof LLMError ? err.code : err instanceof Error ? err.message.slice(0, 120) : "error";
    return { ok: false, mode: "llm", note: `Scene regeneration failed (${detail}); the scene is unchanged.` };
  }
}

/** Rebuild planJson from the current scene rows (after manual edits). */
export async function refreshPlanJson(planId: string, userId: string): Promise<void> {
  const planRow = await db.studioPlan.findFirst({ where: { id: planId, userId } });
  if (!planRow?.planJson) return;
  const plan = JSON.parse(planRow.planJson) as ProductionPlan;
  const rows = await db.studioScene.findMany({ where: { planId }, orderBy: { sceneNumber: "asc" } });
  const scenes: PlanScene[] = rows.map((r) => ({
    sceneNumber: r.sceneNumber,
    durationSec: r.durationSec,
    narration: r.narration,
    visualDescription: r.visualDescription,
    footageNeed: r.footageNeed,
    brollNote: r.brollNote,
    onScreenText: r.onScreenText,
    captionText: r.captionText,
    audioNote: r.audioNote,
    transition: safeTransition(r.transition),
  }));
  const updated: ProductionPlan = { ...plan, schemaVersion: PRODUCTION_PLAN_SCHEMA_VERSION, scenes, fullScript: scenes.map((s) => s.narration).join("\n\n") || plan.fullScript };
  await db.studioPlan.update({ where: { id: planId }, data: { planJson: JSON.stringify(updated), sceneCount: scenes.length } });
}

const TRANSITIONS = ["CUT", "CROSS_DISSOLVE", "FADE_TO_BLACK", "FADE_FROM_BLACK", "WIPE_LEFT", "WIPE_RIGHT", "SLIDE_LEFT", "SLIDE_RIGHT"] as const;
function safeTransition(t: string): PlanScene["transition"] {
  return (TRANSITIONS as readonly string[]).includes(t) ? (t as PlanScene["transition"]) : "CUT";
}

// ── deterministic outline (labeled; same schema) ────────────────────────────
function deterministicPlan(brief: StudioBrief): ProductionPlan {
  const count = targetSceneCount(brief);
  const per = Math.max(2, Math.min(12, Math.floor(brief.durationSec / count)));
  const lang = LANGUAGE_NAMES[brief.language];
  const scenes: PlanScene[] = [];
  for (let i = 1; i <= count; i++) {
    const role = i === 1 ? "Hook" : i === count ? "Closing + call to action" : `Point ${i - 1} of ${count - 2}`;
    scenes.push({
      sceneNumber: i,
      durationSec: per,
      narration:
        i === 1
          ? `${brief.topic} — here is what matters.`
          : i === count
            ? `That is ${brief.topic}. Follow for more.`
            : `${brief.topic}: aspect ${i - 1} of ${count - 2} for ${brief.audience || "your audience"}.`,
      visualDescription: `${brief.visualStyle} visual for ${role.toLowerCase()}`,
      footageNeed: brief.keywords[i - 2] ?? brief.topic.slice(0, 80),
      brollNote: "",
      onScreenText: i === 1 ? brief.topic.slice(0, 60) : "",
      captionText: brief.captionsEnabled ? "" : "",
      audioNote: `Music mood: ${brief.musicMood}`,
      transition: i === 1 ? "FADE_FROM_BLACK" : "CUT",
    });
  }
  return ProductionPlanSchema.parse({
    schemaVersion: PRODUCTION_PLAN_SCHEMA_VERSION,
    topicSummary: `${brief.topic} — ${lang} ${brief.objective} video for ${PLATFORM_PROFILES[brief.platform].label}.`,
    hook: scenes[0].narration,
    intro: scenes[0].narration,
    scenes,
    musicMood: brief.musicMood,
    closingCta: "Follow for more.",
    fullScript: scenes.map((s) => s.narration).join("\n\n"),
    sources: [],
  });
}

/** Estimated total speech duration for a plan (honest heuristic disclosure). */
export function estimatedNarrationSeconds(plan: ProductionPlan, language: "en" | "ta"): number {
  return plan.scenes.reduce((m, s) => m + estimateSpeechSec(s.narration, language), 0);
}
