/**
 * Scene-level operations — POST /api/studio/plans/[planId]/scenes/[sceneId]
 * { action: "regenerate" | "narrate" | "generate-video" | "generate-image" | "assign-asset" }
 * All actions pass through the real backend operations (M8.1 §4/§5/§6/§7).
 * Narration/footage generation carry the external-processing disclosure.
 */
import { NextRequest, NextResponse } from "next/server";
import { z } from "zod";
import { getCurrentUser } from "@/lib/auth";
import { badRequest, notFound, unauthorized } from "@/lib/process-helpers";
import { regenerateScene } from "@/lib/studio/planner";
import { generateSceneNarration, voiceSupport } from "@/lib/studio/narration";
import { generateSceneFootage, generateSceneImage, assignSceneAsset } from "@/lib/studio/assets";
import { db } from "@/lib/db";

export const runtime = "nodejs";
export const maxDuration = 300;

const ActionSchema = z.object({
  action: z.enum(["regenerate", "narrate", "generate-video", "generate-image", "assign-asset"]),
  instruction: z.string().max(300).optional(),
  assetId: z.string().max(64).optional(),
  voice: z.string().max(60).optional(),
  speed: z.number().min(0.5).max(2).optional(),
});

export async function POST(req: NextRequest, ctx: { params: Promise<{ planId: string; sceneId: string }> }) {
  const user = await getCurrentUser();
  if (!user) return unauthorized();
  const { planId, sceneId } = await ctx.params;
  const parsed = ActionSchema.safeParse(await req.json().catch(() => null));
  if (!parsed.success) return badRequest(`Invalid scene action: ${parsed.error.issues.map((i) => i.message).join("; ")}`);

  const scene = await db.studioScene.findFirst({ where: { id: sceneId, userId: user.id, planId } });
  if (!scene) return notFound();

  try {
    switch (parsed.data.action) {
      case "regenerate": {
        const r = await regenerateScene(user.id, planId, sceneId, parsed.data.instruction);
        return r.ok ? NextResponse.json(r) : badRequest(r.note);
      }
      case "narrate": {
        const voice = parsed.data.voice ?? "tongtong";
        const plan = await db.studioPlan.findFirst({ where: { id: planId, userId: user.id } });
        const language = plan ? (JSON.parse(plan.briefJson) as { language: "en" | "ta" }).language : "en";
        const support = voiceSupport(language, voice);
        if (!support.ok) return badRequest(`Narration unavailable: ${support.note}`);
        const r = await generateSceneNarration(user.id, planId, sceneId, voice, parsed.data.speed ?? 1.0);
        return NextResponse.json({
          ...r,
          disclosure: "Narration is generated by an EXTERNAL provider (text sent for speech synthesis). The audio is stored in your media library with provenance.",
        });
      }
      case "generate-video": {
        const r = await generateSceneFootage(user.id, planId, sceneId);
        return NextResponse.json({ ...r, disclosure: "Footage generation sends the scene's visual description to an EXTERNAL provider (metered). Output is provenance-registered." });
      }
      case "generate-image": {
        const r = await generateSceneImage(user.id, planId, sceneId);
        return NextResponse.json({ ...r, disclosure: "Image generation sends the scene's visual description to an EXTERNAL provider (metered). Output is provenance-registered." });
      }
      case "assign-asset": {
        if (!parsed.data.assetId) return badRequest("assign-asset requires assetId.");
        const r = await assignSceneAsset(user.id, planId, sceneId, parsed.data.assetId);
        return NextResponse.json(r);
      }
    }
  } catch (err) {
    return badRequest(err instanceof Error ? err.message.slice(0, 300) : "scene action failed");
  }
}
